"""Write a local development config with this checkout/hardware identities. No DB writes."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "validator")]

from benchmark import machine_identity  # noqa: E402

import fingerprint  # noqa: E402


def fixture_lines(
    fixture_id: str, target: Path, samples_per_run: int, assets_dir: Path
) -> list[str]:
    manifest_path = target / "manifest.json"
    if not manifest_path.is_file():
        raise ValueError(f"missing sample-addressable fixture {target}")
    manifest = json.loads(manifest_path.read_text())
    if manifest["format"] != "sample-addressable-f32-v1" or manifest["workload_id"] != fixture_id:
        raise ValueError(f"unsupported fixture format: {target}")
    assets_dir = assets_dir.resolve()
    asset_paths = {}
    for name, digest_key in (
        ("weights_path", "weights_sha256"),
        ("samples_path", "samples_sha256"),
    ):
        relative = Path(manifest[name])
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError(f"fixture asset path must stay inside {assets_dir}: {relative}")
        path = (assets_dir / relative).resolve()
        path.relative_to(assets_dir)
        if not path.is_file():
            raise ValueError(f"missing fixture asset: {path}")
        if hashlib.sha256(path.read_bytes()).hexdigest() != manifest[digest_key]:
            raise ValueError(f"fixture asset checksum mismatch: {path}")
        asset_paths[name] = path
    weights = asset_paths["weights_path"]
    samples = asset_paths["samples_path"]
    return [
        "",
        "[[benchmark.real_workloads]]",
        f"id = {fixture_id!r}",
        f"family = {manifest['family']!r}",
        f"model = {manifest['model']!r}",
        f"dataset = {manifest['dataset']!r}",
        f"adapter = {manifest['adapter']!r}",
        f"weights_path = {weights.relative_to(ROOT).as_posix()!r}",
        f"weights_sha256 = {manifest['weights_sha256']!r}",
        f"samples_path = {samples.relative_to(ROOT).as_posix()!r}",
        f"samples_sha256 = {manifest['samples_sha256']!r}",
        "asset_revision = "
        + repr(
            hashlib.sha256(
                (manifest["weights_sha256"] + manifest["samples_sha256"]).encode()
            ).hexdigest()
        ),
        f"sample_count = {manifest['sample_count']}",
        f"sample_words = {manifest['sample_words']}",
        f"samples_per_run = {samples_per_run}",
    ]


# The scored small-device boards. Transformer stays selectable with --board for kernel
# experiments, but is not generated by default and is not part of overall.
FAMILIES = ("mlp", "resnet", "mobilenet", "normalized_mlp", "mixer", "recurrent")
BOARDS = ("overall", *FAMILIES, "transformer")


def fixtures_for_adapter(
    assets_dir: Path, adapter: str, subdir: str = "models", *, strict: bool = False
) -> list[tuple[str, Path]]:
    """Manifests under `assets_dir/subdir` for `adapter`; `strict` rejects any other adapter."""
    fixtures = []
    seen_ids = set()
    for manifest_path in sorted((assets_dir / subdir).glob("**/manifest.json")):
        manifest = json.loads(manifest_path.read_text())
        if manifest.get("adapter") != adapter:
            if strict:
                raise ValueError(f"{manifest_path} uses adapter {manifest.get('adapter')!r}")
            continue
        fixture_id = manifest.get("workload_id")
        if not isinstance(fixture_id, str) or fixture_id in seen_ids:
            raise ValueError(f"missing or duplicate workload_id in {manifest_path}: {fixture_id!r}")
        seen_ids.add(fixture_id)
        fixtures.append((fixture_id, manifest_path.parent))
    return fixtures


def board_counts(values: list[str], selected: list[str], option: str) -> dict[str, int]:
    """Parse repeatable board=count settings and reject ambiguous profiles."""
    result = {}
    for value in values:
        try:
            board, raw_count = value.split("=", 1)
            count = int(raw_count)
        except (ValueError, TypeError):
            raise ValueError(f"{option} expects BOARD=COUNT, got {value!r}") from None
        if board not in selected:
            raise ValueError(f"{option} names inactive board {board!r}")
        if board in result:
            raise ValueError(f"{option} repeats board {board!r}")
        if count < 1:
            raise ValueError(f"{option} counts must be positive")
        result[board] = count
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--environment", default="local")
    parser.add_argument(
        "--assets-dir",
        type=Path,
        default=Path(os.environ.get("TORCHLEAN_BENCHMARK_ASSETS", ROOT / "data/benchmark/assets")),
        help="local fixture bundle (default: data/benchmark/assets; "
        "may be overridden by TORCHLEAN_BENCHMARK_ASSETS)",
    )
    parser.add_argument(
        "--quick", action="store_true", help="development only: one paired and baseline round"
    )
    parser.add_argument("--rounds", type=int, default=12, help="paired observations per workload")
    parser.add_argument(
        "--inner", type=int, default=1, help="fresh processes per paired observation"
    )
    parser.add_argument(
        "--baseline-rounds", type=int, default=3, help="baseline telemetry observations"
    )
    parser.add_argument(
        "--mlp-benchmark-seconds",
        type=int,
        default=3600,
        help="independent MLP board benchmark timeout in seconds",
    )
    parser.add_argument(
        "--family-benchmark-seconds",
        type=int,
        default=3600,
        help="independent non-MLP family board benchmark timeout in seconds",
    )
    parser.add_argument(
        "--overall-benchmark-seconds",
        type=int,
        default=3600,
        help="independent overall board benchmark timeout in seconds",
    )
    parser.add_argument(
        "--run-seconds",
        type=int,
        default=3600,
        help="maximum time for one fresh-process benchmark invocation",
    )
    parser.add_argument(
        "--reuse-board-timings",
        action="store_true",
        help="bundle boards and reuse shared candidate timing observations",
    )
    parser.add_argument(
        "--reuse-completed-jobs",
        action="store_true",
        help="reuse earlier completed database measurements with identical requests",
    )
    parser.add_argument(
        "--min-rounds", type=int, help="minimum paired rounds required for admission"
    )
    parser.add_argument(
        "--enable-regression-guard",
        action="store_true",
        help="require every workload/device ratio to pass the regression threshold",
    )
    parser.add_argument(
        "--board-rounds",
        action="append",
        default=[],
        metavar="BOARD=COUNT",
        help="override paired rounds on an active board; repeat as needed",
    )
    parser.add_argument(
        "--board-rounds-json",
        type=json.loads,
        default={},
        metavar="OBJECT",
        help="JSON object mapping active boards to paired-round counts",
    )
    parser.add_argument(
        "--board-baseline-rounds",
        action="append",
        default=[],
        metavar="BOARD=COUNT",
        help="override baseline telemetry rounds on an active board",
    )
    parser.add_argument(
        "--board-baseline-rounds-json",
        type=json.loads,
        default={},
        metavar="OBJECT",
        help="JSON object mapping active boards to baseline-round counts",
    )
    parser.add_argument(
        "--reference", type=Path, default=ROOT / "kernels/exact/incumbent/Kernel.lean"
    )
    parser.add_argument(
        "--dev-intake",
        action="store_true",
        help="development deployment only: also evaluate uploads the API tagged dev",
    )
    parser.add_argument("--board", choices=BOARDS)
    parser.add_argument(
        "--real-image-zoo",
        action="store_true",
        help="include local trained image-zoo fixtures in the scored real suite",
    )
    parser.add_argument(
        "--real-uci-har",
        action="store_true",
        help="include local UCI-HAR sensor fixtures in the scored real suite",
    )
    parser.add_argument(
        "--real-appliance-mixer",
        action="store_true",
        help="include the local Appliance Energy Mixer fixture in the scored real suite",
    )
    parser.add_argument(
        "--real-recurrent",
        action="store_true",
        help="include every local recurrent-v1 fixture under models/recurrent in the real suite",
    )
    parser.add_argument(
        "--synthetic-full",
        action="store_true",
        help="include every supported synthetic batch/kind cell instead of batch-1 defaults",
    )
    parser.add_argument(
        "--synthetic-cell",
        action="append",
        help="explicit synthetic cell to score; repeat to build a custom compact suite",
    )
    args = parser.parse_args()
    if args.output.exists():
        parser.error("output already exists; edit it or choose a new path")
    source = args.reference.resolve()
    assets_dir = args.assets_dir if args.assets_dir.is_absolute() else ROOT / args.assets_dir
    assets_dir = assets_dir.resolve()
    try:
        assets_dir.relative_to(ROOT.resolve())
    except ValueError:
        parser.error(
            "--assets-dir must be inside this repository so workers can sandbox the assets"
        )
    proof, bench = fingerprint.proof(), fingerprint.benchmark()
    rounds, inner, baseline_rounds = (
        (1, 1, 1) if args.quick else (args.rounds, args.inner, args.baseline_rounds)
    )
    if min(rounds, inner, baseline_rounds) < 1:
        parser.error("round and process counts must be positive")
    if (
        min(
            args.mlp_benchmark_seconds,
            args.family_benchmark_seconds,
            args.overall_benchmark_seconds,
            args.run_seconds,
        )
        < 1
    ):
        parser.error("board benchmark timeouts must be positive")
    min_rounds = args.min_rounds if args.min_rounds is not None else min(5, rounds)
    names = list(FAMILIES)
    family_order = [name for name in names if name != "recurrent"] + (
        ["recurrent"] if "recurrent" in names else []
    )
    selected = [args.board] if args.board else [*family_order, "overall"]
    try:
        if not isinstance(args.board_rounds_json, dict) or not isinstance(
            args.board_baseline_rounds_json, dict
        ):
            raise ValueError("board round JSON options must be objects")
        board_round_values = args.board_rounds + [
            f"{board}={count}" for board, count in args.board_rounds_json.items()
        ]
        board_baseline_values = args.board_baseline_rounds + [
            f"{board}={count}" for board, count in args.board_baseline_rounds_json.items()
        ]
        board_round_overrides = board_counts(board_round_values, selected, "--board-rounds")
        board_baseline_overrides = board_counts(
            board_baseline_values, selected, "--board-baseline-rounds"
        )
    except ValueError as exc:
        parser.error(str(exc))
    effective_rounds = {board: board_round_overrides.get(board, rounds) for board in selected}
    if not 1 <= min_rounds <= min(effective_rounds.values()):
        parser.error("--min-rounds must not exceed paired rounds on any active board")
    if any(count > effective_rounds[board] for board, count in board_baseline_overrides.items()):
        parser.error("board baseline rounds must not exceed paired rounds")
    synthetic_models = [args.board] if args.board and args.board != "overall" else list(FAMILIES)
    if args.synthetic_cell:
        synthetic_cells = args.synthetic_cell
    else:
        kinds = ("normal", "wide", "sparse")
        synthetic_cells = [
            f"{model}:b{batch}:{kind}"
            for model in synthetic_models
            for batch in (
                ((1, 8) if model in ("mlp", "normalized_mlp") else (1, 4))
                if args.synthetic_full
                else (1,)
            )
            for kind in kinds
        ]

    real_suite = (
        args.real_image_zoo or args.real_uci_har or args.real_appliance_mixer or args.real_recurrent
    )
    lines = [
        "# Development configuration; calibrate production settings before enabling payouts.",
        f"proof_identity = {proof!r}",
        f"benchmark_identity = {bench!r}",
        "seeds = [42]" if args.quick else "seed_count = 1",
        f"seed_mode = {'fixed' if args.quick else 'fresh'!r}",
        "retry_seconds = 300",
        "lease_seconds = 120",
        "alert_seconds = 900",
        "verification_seconds = 1800",
        f"dev_intake = {'true' if args.dev_intake else 'false'}",
        "",
        "[benchmark]",
        'suites = ["synthetic", "real"]' if real_suite else 'suites = ["synthetic"]',
        f"synthetic_cells = {synthetic_cells!r}",
        "suite_weights = { synthetic = 0.5, real = 0.5 }"
        if real_suite
        else "suite_weights = { synthetic = 1.0 }",
        f"reuse_board_timings = {str(args.reuse_board_timings).lower()}",
        f"reuse_completed_jobs = {str(args.reuse_completed_jobs).lower()}",
        "",
        "[timing]",
        f"rounds = {rounds}",
        f"inner = {inner}",
        f"baseline_rounds = {baseline_rounds}",
        f"run_seconds = {args.run_seconds}",
        "# Build and measurement limits default by architecture and model count.",
        "",
        "[admission]",
        "bar = 0.97",
        "guard = 1.10",
        f"guard_enabled = {str(args.enable_regression_guard).lower()}",
        "draws = 2000",
        "quantile = 0.05",
        f"min_rounds = {min_rounds}",
        "",
        f"[environments.{args.environment}]",
        "weight = 1.0",
        f"identity = {machine_identity()!r}",
        f"architecture = {platform.machine()!r}",
        "",
        "[rewards]",
        "rank_shares = [1.0, 0.0]",
        "paused_policy = 'preserve'",
        "",
        "[rewards.board_weights]",
    ]
    lines += [
        f"{name} = {1.0 if args.board else 0.5 if name == 'overall' else 0.5 / len(names)}"
        for name in selected
    ]
    for board in selected:
        lines += ["", f"[boards.{board}.models]"]
        lines += [
            f"{name} = {1 / len(names) if board == 'overall' else 1.0}"
            for name in (names if board == "overall" else [board])
        ]
        lines += [
            "",
            f"[boards.{board}.reference]",
            f"path = {str(source)!r}",
            f"sha256 = {hashlib.sha256(source.read_bytes()).hexdigest()!r}",
            "",
            f"[boards.{board}.timing]",
            "benchmark_seconds = "
            + str(
                args.overall_benchmark_seconds
                if board == "overall"
                else args.mlp_benchmark_seconds
                if board == "mlp"
                else args.family_benchmark_seconds
            ),
        ]
        if board in board_round_overrides:
            lines.append(f"rounds = {board_round_overrides[board]}")
        if board in board_baseline_overrides:
            lines.append(f"baseline_rounds = {board_baseline_overrides[board]}")
    if args.real_image_zoo:
        fixtures = fixtures_for_adapter(assets_dir, "image-zoo-v1")
        if not fixtures:
            parser.error(f"--real-image-zoo requires fixtures under {assets_dir / 'models'}")
        for fixture_id, target in fixtures:
            lines += fixture_lines(fixture_id, target, 1, assets_dir)
    if args.real_uci_har:
        fixtures = fixtures_for_adapter(assets_dir, "uci-har-v1")
        if not fixtures:
            parser.error(f"--real-uci-har requires fixtures under {assets_dir / 'models'}")
        for fixture_id, target in fixtures:
            lines += fixture_lines(fixture_id, target, 1, assets_dir)
    if args.real_appliance_mixer:
        fixtures = fixtures_for_adapter(assets_dir, "appliance-mixer-v1")
        if not fixtures:
            parser.error(f"--real-appliance-mixer requires fixtures under {assets_dir / 'models'}")
        for fixture_id, target in fixtures:
            lines += fixture_lines(fixture_id, target, 1, assets_dir)
    if args.real_recurrent:
        try:
            fixtures = fixtures_for_adapter(
                assets_dir, "recurrent-v1", "models/recurrent", strict=True
            )
        except ValueError as exc:
            parser.error(f"--real-recurrent: {exc}")
        if not fixtures:
            parser.error(
                f"--real-recurrent requires fixtures under {assets_dir / 'models/recurrent'}"
            )
        for fixture_id, target in fixtures:
            lines += fixture_lines(fixture_id, target, 1, assets_dir)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(args.output)


if __name__ == "__main__":
    main()
